"""Gemini Omni Flash clips for the daily Short.

Google shut the Veo 3.1 preview models down on 22-Oct-2026 (https://ai.google.dev/gemini-api/docs/video: "migrate to
Gemini Omni Flash"); every daily run from 22 to 27-Oct died on `404 ... veo-3.1-generate-preview is no longer
available`, and the Kling fallback could not help (fal.ai account locked: balance exhausted).

Official shape (https://ai.google.dev/gemini-api/docs/omni, read 28-Oct-2026):
- POST /v1beta/interactions {model: "gemini-omni-1.1-flash", input: <text>, response_format: {type: "video",
  aspect_ratio: "9:16"|"16:9", resolution: "720p" (default) ...}}; a plain call is synchronous and returns the mp4 as
  base64 (`output_video.data`, or a `model_output` step with a `video` item). With delivery "uri" it returns a file to
  poll until ACTIVE and download.
- No duration or negative-prompt field: length, "one continuous shot" (Omni cuts between shots by default) and the
  "no dialogue / no text" negatives go in the prompt. Audio is generated by default.
- Price (https://ai.google.dev/gemini-api/docs/pricing): $17.50 per 1M output video tokens, billed at 5,792 tokens per
  second of 720p video, i.e. about $0.10 per second.

python -m tools.omni_video --probe out.mp4 makes one short test clip and prints what came back.
"""
import base64
import json
import os
import re
import subprocess
import sys
import time

import requests

API = "https://generativelanguage.googleapis.com/v1beta"
MODEL = "gemini-omni-1.1-flash"
PRICE_PER_SECOND = 17.50 / 1_000_000 * 5792
RESOLUTION = "720p"
REQUEST_TIMEOUT = 600

_GONE = re.compile(r"no longer available|not found|is not supported|unsupported model|does not exist|not available for|"
                   r"has been (?:shut ?down|retired|deprecated)", re.I)
_BLOCKED = re.compile(r"safety|blocked|policy|violat|prohibited|responsible ai", re.I)


def clip_prompt(prompt, seconds):
    """The scene, then the rules Veo used to get from its config: one shot, the length, no talk, no writing."""
    return (f"{str(prompt or '').strip()}\n\n"
            f"In a single continuous shot, no scene cuts, about {int(seconds)} seconds long, vertical 9:16 framing. "
            "Sound: quiet natural ambience only. No dialogue, no voices, no narration, no music. "
            "No text, captions, subtitles, labels, logos or writing anywhere in the frame.")


def _find_video(node):
    """The first {"type": "video", "data"|"uri": ...} item anywhere in an interaction."""
    if isinstance(node, dict):
        if (node.get("type") == "video" or str(node.get("mime_type") or node.get("mimeType") or "").startswith("video/")) \
                and (node.get("data") or node.get("uri")):
            return node
        for key in ("output_video", "outputVideo"):
            if isinstance(node.get(key), dict) and (node[key].get("data") or node[key].get("uri")):
                return node[key]
        for value in node.values():
            found = _find_video(value)
            if found:
                return found
    elif isinstance(node, list):
        for value in node:
            found = _find_video(value)
            if found:
                return found
    return None


def _download(uri, api_key, path, deadline):
    name = None
    m = re.search(r"files/([^/:?]+)", uri)
    if m:
        name = m.group(1)
        while time.time() < deadline:
            r = requests.get(f"{API}/files/{name}", params={"key": api_key}, timeout=30)
            state = (r.json() if r.ok else {}).get("state", "ACTIVE" if r.status_code == 404 else "")
            if state in ("ACTIVE", "") or r.status_code == 404:
                break
            if state == "FAILED":
                raise RuntimeError("file processing failed")
            time.sleep(5)
    url = uri if uri.startswith("http") else f"{API}/files/{name}:download?alt=media"
    r = requests.get(url, params={"key": api_key}, timeout=180)
    r.raise_for_status()
    with open(path, "wb") as f:
        f.write(r.content)
    return len(r.content)


def probe_seconds(path):
    try:
        out = subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "json", path],
                             capture_output=True, text=True, timeout=30)
        return float(json.loads(out.stdout or "{}").get("format", {}).get("duration") or 0)
    except Exception:
        return 0.0


def generate_clip(prompt, path, *, seconds=8, api_key=None, aspect_ratio="9:16", resolution=RESOLUTION,
                  timeout=REQUEST_TIMEOUT):
    """One clip to `path`. Returns {"ok", "kind", "message", "bytes", "seconds", "cost"}; kind is "ok", "gone" (the model
    itself is unavailable: never retry it), "rate" (429), "blocked" (the prompt was refused: a retry of the same prompt
    will not pass) or "error" (worth another try)."""
    api_key = api_key or os.environ.get("GOOGLE_API_KEY", "")
    out = {"ok": False, "kind": "error", "message": "", "bytes": 0, "seconds": 0.0, "cost": 0.0}
    if not api_key:
        out.update(kind="gone", message="GOOGLE_API_KEY not set")
        return out
    body = {"model": MODEL, "input": clip_prompt(prompt, seconds), "store": False,
            "response_format": {"type": "video", "aspect_ratio": aspect_ratio, "resolution": resolution}}
    deadline = time.time() + timeout
    try:
        r = requests.post(f"{API}/interactions", params={"key": api_key}, json=body, timeout=timeout)
    except requests.RequestException as error:
        out["message"] = f"request failed: {type(error).__name__}: {str(error)[:160]}"
        return out
    text = r.text[:600]
    if r.status_code == 429 or "RESOURCE_EXHAUSTED" in text:
        out.update(kind="rate", message=f"HTTP {r.status_code} rate limited: {text[:200]}")
        return out
    if r.status_code >= 400:
        kind = "gone" if r.status_code in (403, 404) or (r.status_code == 400 and _GONE.search(text)) else \
            "blocked" if r.status_code == 400 and _BLOCKED.search(text) else "error"
        out.update(kind=kind, message=f"HTTP {r.status_code}: {text[:300]}")
        return out
    try:
        data = r.json()
    except ValueError:
        out["message"] = f"not JSON: {text[:200]}"
        return out
    status = str(data.get("status") or "completed").lower()
    while status in ("in_progress", "queued", "pending", "running") and data.get("id") and time.time() < deadline:
        time.sleep(10)
        g = requests.get(f"{API}/interactions/{data['id']}", params={"key": api_key}, timeout=120)
        if not g.ok:
            out["message"] = f"poll HTTP {g.status_code}: {g.text[:200]}"
            return out
        data = g.json()
        status = str(data.get("status") or "completed").lower()
    if status not in ("completed", "succeeded", "done"):
        blob = json.dumps(data)[:400]
        out.update(kind="blocked" if _BLOCKED.search(blob) else "error", message=f"status {status}: {blob}")
        return out
    video = _find_video(data)
    if not video:
        blob = json.dumps(data)[:400]
        out.update(kind="blocked" if _BLOCKED.search(blob) else "error", message=f"no video in the answer: {blob}")
        return out
    try:
        if video.get("data"):
            raw = base64.b64decode(video["data"])
            with open(path, "wb") as f:
                f.write(raw)
            size = len(raw)
        else:
            size = _download(video["uri"], api_key, path, deadline)
    except Exception as error:
        out["message"] = f"saving the video failed: {type(error).__name__}: {str(error)[:160]}"
        return out
    if size < 10_000:
        out["message"] = f"video too small ({size} bytes)"
        return out
    secs = probe_seconds(path)
    out.update(ok=True, kind="ok", message="ok", bytes=size, seconds=secs,
               cost=round((secs or float(seconds)) * PRICE_PER_SECOND, 4))
    return out


def _probe(path):
    started = time.time()
    result = generate_clip("A neatly folded plain black cotton T-shirt resting on a light wooden table in soft daylight; "
                           "the camera slowly pushes in.", path, seconds=4)
    info = {"result": result, "elapsed_s": round(time.time() - started, 1)}
    if result["ok"]:
        streams = subprocess.run(["ffprobe", "-v", "error", "-show_entries", "stream=codec_type,width,height,r_frame_rate",
                                  "-of", "json", path], capture_output=True, text=True, timeout=30)
        info["streams"] = json.loads(streams.stdout or "{}").get("streams")
    print(json.dumps(info, indent=1))
    return 0 if result["ok"] else 1


if __name__ == "__main__":
    if len(sys.argv) == 3 and sys.argv[1] == "--probe":
        sys.exit(_probe(sys.argv[2]))
    print("usage: python -m tools.omni_video --probe out.mp4")
    sys.exit(2)
